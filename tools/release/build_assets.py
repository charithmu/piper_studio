#!/usr/bin/env python3
"""Build the data of the `piper_assets` wheel from this workspace (needs the ROS environment: xacro, piper_description, piper_sim).

    source scripts/env.sh && python tools/release/build_assets.py [--out src/piper_assets/piper_assets/data]

Writes, for downstream users that have no ROS (`pip install piper_assets`):
  piper_{none,zedxm}_w{0.0,0.07}.urdf   flat URDF, no prefix (joint1 .. joint6, base_link, tcp_link), gripper fixed at that width
  piper_{none,zedxm}_open.urdf          the same with the moving gripper (mimic fingers); `piper_assets.urdf_path(width)` makes other widths from it
  piper_{none,zedxm}.srdf               the expanded SRDF (self-collision pairs)
  meshes/<package>/...                 every mesh the URDFs use (visual .dae and collision .stl), referenced by relative paths
  limits.json                          position (hard and planning), velocity, acceleration, jerk, effort, each with its source
  scene.json                           the shared scene objects and the placeholder table
  camera_mounts/*.yaml                 the bracket versions (poses)
  curobo/                              the cuRobo models (piper_{none,zedxm}.yml + provenance, validation, quality; committed in src/piper_description/config/curobo/,
                                       regenerated by tools/curobo/build_model.py: optional, needs the cuRobo environment) and planner_defaults.json
  go2_piper_{open,w0.0,w0.07}.urdf, go2_piper.srdf, go2/world_{base,arm_base}.json, go2/cover_report.json, go2/mount.json
                                       the full setup on the Go2 (only if go2_studio's unitree_ros checkout is there): same arm names, the Go2's links (base, FL_hip, ...) beside them,
                                       the world (the dog as one generated box + the plate and payload boxes) in both frames (the arm-frame one is what cuRobo plans in), the NOMINAL mount and the stand pose; Go2 meshes under meshes/go2_description
  camera.json                          the simulated ZED X Mini: intrinsics, size, frames, pose in gripper_base and the TCP
  licenses/                            licence texts of the third-party meshes
  manifest.json                        version, source commit, file hashes
The result is generated: it is git-ignored and built into the wheel by scripts/build_wheels.sh. A test compares it with a fresh expansion.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

import xacro
import yaml

WS = Path(__file__).resolve().parents[2]
GO2_PKG = Path.home() / "projects/ros/go2_studio/third_party/unitree_ros/robots/go2_description"   # external input: the Go2 description (Unitree, BSD-3)
MARGIN = 0.01
GRIPPER_WIDTHS = (0.0, 0.07)
CAMERAS = ("none", "zedxm")
JERK = 25.0   # rad/s^3: derived (5 rad/s^2 reached in 0.2 s), NOT in the firmware or any datasheet


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def git_state() -> dict:
    def run(*a):
        return subprocess.run(["git", "-C", str(WS), *a], capture_output=True, text=True).stdout.strip()
    return {"commit": run("rev-parse", "HEAD"), "describe": run("describe", "--tags", "--always", "--dirty"), "dirty": bool(run("status", "--porcelain", "--", "src", "tools"))}


def localise_meshes(urdf: str, out: Path) -> str:
    """Copy every mesh into out/meshes/<package>/<path in the package share> and point the URDF at it with a relative path."""
    from ament_index_python.packages import get_package_share_directory

    def resolve(name: str) -> Path:
        name = name.removeprefix("file://")
        if name.startswith("package://go2_description/"):
            return GO2_PKG / name[len("package://go2_description/"):]
        if name.startswith("package://"):
            pkg, rest = name[len("package://"):].split("/", 1)
            return Path(get_package_share_directory(pkg)) / rest
        return Path(name)

    def rewrite(m):
        src = resolve(m.group(1))   # not resolved: a symlink install would lose the share/<pkg> part
        if m.group(1).startswith("package://go2_description/"):          # the Go2's (Unitree) meshes, not in an ament share
            rest = Path(m.group(1)[len("package://go2_description/"):])
            dst = out / "meshes" / "go2_description" / rest
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
            return f'filename="meshes/go2_description/{rest.as_posix()}"'
        parts = src.parts
        i = len(parts) - 1 - parts[::-1].index("share")          # .../install/<pkg>/share/<pkg>/<rest>
        pkg, rest = parts[i + 1], Path(*parts[i + 2:])
        if pkg == "agx_arm_description":
            rest = Path(*rest.parts[1:]) if rest.parts[0] == "agx_arm_urdf" else rest
        dst = out / "meshes" / pkg / rest
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        return f'filename="meshes/{pkg}/{rest.as_posix()}"'

    return re.sub(r'filename="([^"]+)"', rewrite, urdf)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=WS / "src/piper_assets/piper_assets/data")
    out = ap.parse_args().out.resolve()
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    from piper_core import fixed_gripper, limits_from_urdf, zero_pose
    from piper_sim import _without_ros2_control, robot_description

    files = {}
    for cam in CAMERAS:
        maps = {"prefix": "", "gripper": True, "camera": cam}      # always explicit: the description's default is the camera
        urdf = _without_ros2_control(robot_description("mujoco", **maps))
        urdf = localise_meshes(urdf, out)
        variants = {f"piper_{cam}_open.urdf": urdf, **{f"piper_{cam}_w{w}.urdf": fixed_gripper(urdf, w, "") for w in GRIPPER_WIDTHS}}
        for name, text in variants.items():
            (out / name).write_text(text)
        root = ET.fromstring(urdf)
        srdf = xacro.process_file(str(WS / "src/piper_control/config/moveit/piper.srdf.xacro"),
                                  mappings={"robot_name": root.get("name"), "prefix": "", "gripper": "true", "camera": cam}).toxml()
        (out / f"piper_{cam}.srdf").write_text(srdf)
        files[cam] = urdf

    setups = ["arm", "arm_cam"]
    if (GO2_PKG / "urdf/go2_description.urdf").exists():          # the full setup on the Go2: same arm names (no prefix), the Go2's links beside them
        from piper_description import arm_base_pose, go2_piper_description, go2_stand_pose, go2_world, setup_config
        g2 = localise_meshes(go2_piper_description(go2_urdf=GO2_PKG / "urdf/go2_description.urdf", prefix="", gripper=True, camera="zedxm"), out)
        for name, text in {"go2_piper_open.urdf": g2, **{f"go2_piper_w{w}.urdf": fixed_gripper(g2, w, "") for w in GRIPPER_WIDTHS}}.items():
            (out / name).write_text(text)
        g2root = ET.fromstring(g2)
        arm_srdf = ET.fromstring((out / "piper_zedxm.srdf").read_text())
        arm_srdf.set("name", g2root.get("name"))
        for a, b in (("base_link", "dock_plate"), ("dock_plate", "base"), ("base_link", "mount")):       # touching by construction
            ET.SubElement(arm_srdf, "disable_collisions", link1=a, link2=b, reason="Adjacent")
        (out / "go2_piper.srdf").write_text(ET.tostring(arm_srdf, encoding="unicode"))
        wd = out / "go2"
        wd.mkdir()
        for frame in ("base", "arm_base"):       # the world: the dog's generated box (tools/go2_cover) + the plate and payload boxes, in the Go2 `base` frame and in the arm's base_link frame (what cuRobo plans in)
            (wd / f"world_{frame}.json").write_text(json.dumps(go2_world(frame), indent=1))
        shutil.copy2(WS / "src/piper_description/config/go2/dog_cover_report.json", wd / "cover_report.json")
        cfg = setup_config()
        (wd / "mount.json").write_text(json.dumps({
            "NOMINAL": "estimates, not measured on the Go2 expansion dock (config/go2/go2_setup.yaml)", **cfg["mount"], "frame": "Go2 `base`",
            "base_in_go2": arm_base_pose().tolist(), "go2_root_link": "base", "stand_pose": go2_stand_pose(), "stand_source": cfg["stand_source"]}, indent=1))
        setups.append("go2")

    # limits with provenance
    root = ET.fromstring(files["none"])
    hard = limits_from_urdf(files["none"])
    joints = [f"joint{i}" for i in range(1, 7)]
    fw = yaml.safe_load((WS / "src/piper_description/config/firmware_values.yaml").read_text())
    pos = {j: {"lower": hard[j][0], "upper": hard[j][1]} for j in joints}
    plan = {j: {"lower": hard[j][0] + MARGIN, "upper": hard[j][1] - MARGIN} for j in joints}
    limits = {
        "joints": joints, "margin": MARGIN,
        "position": {"values": pos, "unit": "rad", "source": "vendor URDF = limits stored in the arm (firmware S-V1.9-1, docs/real_arm/arms/piper-01.md)"},
        "planning_position": {"values": plan, "unit": "rad", "source": f"position shrunk by the guard margin {MARGIN} rad: a trajectory inside these is executed unchanged"},
        "velocity": {"value": fw["arm_joint_max_velocity"], "unit": "rad/s", "source": "firmware (max_joint_spd), measured on the arm"},
        "acceleration": {"value": 5.0, "unit": "rad/s^2", "source": "firmware (stored limit)"},
        "jerk": {"value": JERK, "unit": "rad/s^3", "source": "DERIVED, no source: 5 rad/s^2 reached in 0.2 s", "flag": "derived"},
        "effort": {"values": dict(zip(joints, fw["arm_joint_max_effort"])), "unit": "N.m",
                   "source": "SDK move_mit torque command range (pyAgxArm firmware_reference), an upper bound",
                   "flag": "not a motor rating"},
        "gripper": {"stroke": fw["gripper_stroke"], "unit": "m", "source": "firmware (max_range_config)"},
        "zero_pose": zero_pose(hard, joints, MARGIN),
        "max_step": 0.15,
    }
    (out / "limits.json").write_text(json.dumps(limits, indent=1))

    scene = yaml.safe_load((WS / "src/piper_sim/config/scene_objects.yaml").read_text())
    (out / "scene.json").write_text(json.dumps({"frame": "base_link", **scene}, indent=1))

    shutil.copytree(WS / "src/piper_description/config/camera_mounts", out / "camera_mounts")
    models = WS / "src/piper_description/config/curobo"
    shutil.copytree(models, out / "curobo") if models.exists() else (out / "curobo").mkdir()
    planner = yaml.safe_load((WS / "tools/curobo/policy.yaml").read_text())["planner"]
    (out / "curobo" / "planner_defaults.json").write_text(json.dumps(planner, indent=1))
    from piper_description import camera_model
    cm = camera_model()
    zed = ET.fromstring(files["zedxm"])
    import numpy as np
    from scipy.spatial.transform import Rotation as Rot
    import sys
    from ament_index_python.packages import get_package_prefix
    sys.path.insert(0, str(Path(get_package_prefix("piper_description")) / "lib" / "piper_description"))
    import model_audit
    (out / "_zed.urdf").write_text(files["zedxm"])
    mm = model_audit.load_urdf("zed", out / "_zed.urdf")
    (out / "_zed.urdf").unlink()
    T_gb = np.linalg.inv(mm.fk({}, "gripper_base")) @ mm.fk({}, cm["optical_frame"])
    T_tcp = np.linalg.inv(mm.fk({}, "tcp_link")) @ mm.fk({}, cm["optical_frame"])
    T_l6 = np.linalg.inv(mm.fk({}, "link6")) @ mm.fk({}, cm["optical_frame"])
    (out / "camera.json").write_text(json.dumps({**{k: v for k, v in cm.items() if k != "link"}, "parent_link": "gripper_base",
                                                 "T_parent_optical": T_gb.tolist(), "T_tcp_optical": T_tcp.tolist(), "T_link6_optical": T_l6.tolist(),
                                                 "calibration": "zedxm_bracket_v3 (nominal, from the user's Fusion measures; not hand-eye calibrated)"}, indent=1))
    lic = out / "licenses"
    lic.mkdir()
    shutil.copy2(WS / "external/agx_arm_ros/LICENSE", lic / "agx_arm_ros-MIT.txt")
    (lic / "NOTICE.txt").write_text(
        "Meshes in meshes/agx_arm_description and the stand/gripper meshes: AgileX Robotics, MIT (agx_arm_ros / agx_arm_sim).\n"
        "meshes/piper_description/zedxm.stl: Stereolabs ZED X Mini, from zed-ros2-description (Apache-2.0, Stereolabs).\n"
        "meshes/piper_description/zedxm_bracket_v*.stl: the user's own clamp bracket (Piper Studio, Apache-2.0).\n"
        "meshes/go2_description (setup go2 only): Unitree Go2 description (unitree_ros), BSD-3-Clause, see licenses/unitree_ros-BSD3.txt.\n"
        "Everything else: Apache-2.0, Piper Studio.\n")
    if "go2" in setups:
        shutil.copy2(GO2_PKG.parents[1] / "LICENSE", lic / "unitree_ros-BSD3.txt")

    tcp = re.search(r'name="tcp_joint".*?<origin[^>]*xyz="([^"]+)"', files["none"], re.S)
    manifest = {
        "source": git_state(), "base_link": "base_link", "tcp_link": "tcp_link", "tcp_xyz_in_gripper_base": [float(v) for v in tcp.group(1).split()] if tcp else None,
        "joint_names": joints, "gripper_widths": list(GRIPPER_WIDTHS), "cameras": list(CAMERAS), "setups": setups, "default_setup": "go2", "robot_name": root.get("name"),
        "files": {str(p.relative_to(out)): sha(p) for p in sorted(out.rglob("*")) if p.is_file()},
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1))
    print(f"{out}: {len(manifest['files'])} files, {sum(p.stat().st_size for p in out.rglob('*') if p.is_file()) / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
